/** Quantos pontos acender para `value`, numa coluna de `rows` pontos. */
export function litDots(value: number, max: number, rows: number): number {
  if (value <= 0 || max <= 0) return 0;
  return Math.min(rows, Math.max(1, Math.round((value / max) * rows)));
}
